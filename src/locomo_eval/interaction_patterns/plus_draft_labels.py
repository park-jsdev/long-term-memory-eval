"""First-pass readings of LoCoMo-Plus cues. Not gold.

A person corrects these in the label dashboard. Each draft is one
explicit cue: Who is speaker A, Why is that cue, What and scope are
the constraint a harness would store. If/When and How/Then are the
H1 decision for the trigger only.
"""

from __future__ import annotations

from typing import Any


def _draft(
    what: str,
    scope: str,
    if_decision: str,
    when: str,
    how_then: str,
    uncertainty: str,
    confidence: str,
    what_type: str = "stable_constraint",
    exceptions: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "who_basis": "explicit",
        "what_type": what_type,
        "what": what,
        "scope": scope,
        "exceptions": list(exceptions or []),
        "if_decision": if_decision,
        "when": when,
        "how_then": how_then,
        "uncertainty": uncertainty,
        "confidence": confidence,
    }


