def run_benchmark(
    predictions: str | Path,
    *,
    out_dir: str | Path,
    autorater: Autorater,
    skip_category: int = ADVERSARIAL_CATEGORY,
    max_questions: int | None = None,
    our_label: str | None = None,
    prompt_version: str | None = None,
) -> dict[str, Any]:
    """Score a prediction JSONL with Mem0 lexical metrics + autorater; write pack."""
    pred_path = resolve_predictions_jsonl(predictions)
    rows = load_prediction_rows(pred_path)
    if max_questions is not None:
        rows = rows[: int(max_questions)]
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    _reset_benchmark_output(out)
    verdict_path = out / "autorater_verdicts.jsonl"

    label = our_label
    if not label and rows:
        label = str(rows[0].get("memory_type") or pred_path.parent.name)
    label = label or "this_run"

    scored: list[dict[str, Any]] = []
    n_ratings = 0
    try:
        for i, pred_row in enumerate(rows, start=1):
            row = score_prediction_for_benchmark(
                pred_row, autorater, skip_category=skip_category
            )
            row["autorater_prompt_version"] = prompt_version
            scored.append(row)
            if not row.get("skipped"):
                n_ratings += 1
            write_jsonl(verdict_path, scored)
            if i % 10 == 0 or i == len(rows):
                print(f"  [{i}/{len(rows)}] ratings={n_ratings}")
    except Exception as exc:
        write_jsonl(verdict_path, scored)
        print(
            f"\nStopped early ({type(exc).__name__}: {exc})\n"
            f"Saved {len(scored)} rows to {verdict_path}\n"
            "Re-run to regenerate the autorater report from the beginning."
        )
        raise

    summary = aggregate_benchmark(scored)
    summary["memory_type"] = label
    summary["autorater_model"] = autorater.model_name
    summary["autorater_provider"] = autorater.provider
    summary["score_kind"] = (
        "mock_sanity_not_llm_judge"
        if autorater.provider == "mock"
        else "llm_as_a_judge"
    )
    if rows:
        summary["reader_model"] = rows[0].get("reader_model")

    meta = {
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "predictions_path": str(pred_path),
        "autorater_model": autorater.model_name,
        "autorater_provider": autorater.provider,
        "temperature": getattr(autorater, "temperature", 0.0),
        "max_tokens": getattr(autorater, "max_tokens", None),
        "autorater_family": (
            resolve_model(autorater.model_name).family
            if autorater.model_name != "mock"
            else "mock"
        ),
        "prompt_version": prompt_version,
        "skip_category": skip_category,
        "n_predictions": len(rows),
        "n_new_ratings": n_ratings,
        "n_new_judge_calls": n_ratings if autorater.provider == "openai" else 0,
        "cite": PAPER_CITE,
        "paper_url": PAPER_URL,
        "package_version": "0.1.5",
    }
    table_paths = write_benchmark_tables(out, summary, scored, our_label=label)
    plot_paths = write_benchmark_plots(
        scored, summary, our_label=label, out_dir=out / "plots"
    )
    write_json(out / "autorater_metrics.json", summary)
    write_json(out / "run_meta.json", meta)
    write_summary_md(
        out / "SUMMARY.md",
        our_label=label,
        summary=summary,
        meta=meta,
        table_paths=table_paths,
        plot_paths=plot_paths,
    )
    return {
        "out_dir": str(out),
        "summary": summary,
        "meta": meta,
        "tables": {k: str(p) for k, p in table_paths.items()},
        "plots": [str(p) for p in plot_paths],
        "n_new_ratings": n_ratings,
        "n_new_judge_calls": n_ratings if autorater.provider == "openai" else 0,
    }


def _resolve_run_paths(run: str | None, predictions: str | None, out: str | None) -> tuple[Path, Path]:
    if predictions:
        pred = resolve_predictions_jsonl(predictions)
        out_dir = Path(out) if out else pred.parent / "autorater"
        return pred, out_dir
    if run:
        run_dir = Path(run)
        if not run_dir.is_absolute() and not run_dir.exists():
            alt = ROOT / "experiments" / run_dir
            if alt.exists():
                run_dir = alt
        pred = resolve_predictions_jsonl(run_dir)
        out_dir = Path(out) if out else pred.parent / "autorater"
        return pred, out_dir
    raise SystemExit("Pass --run experiments/<run_id> or --predictions path/to/predictions.jsonl")


def main(argv: list[str] | None = None) -> None:
    loaded = load_env()
    if loaded is not None:
        print(f"Loaded env from {loaded}")

    p = argparse.ArgumentParser(
        description=(
            "Mem0 LLM-as-a-Judge autorater + F1/BLEU-1 on a finished run pack "
            "(tables, histograms, box-whisker, latency vs literature)."
        )
    )
    p.add_argument("--run", default=None, help="experiments/<run_id> directory or id")
    p.add_argument("--predictions", default=None, help="predictions.jsonl (overrides --run)")
    p.add_argument("--out", default=None, help="Output directory (default: <run>/autorater)")
    p.add_argument(
        "--config",
        default="configs/autorater.yaml",
        help="Autorater YAML (model, prompt, skip_category)",
    )
    p.add_argument("--autorater", default=None, help="openai | mock (overrides YAML provider)")
    p.add_argument("--model", default=None, help="Judge model id (default: gpt-4o-mini)")
    p.add_argument("--prompt", default=None, help="Override judge prompt path")
    p.add_argument("--temperature", type=float, default=None, help="Override judge temperature")
    p.add_argument("--max-tokens", type=int, default=None, help="Override judge completion-token limit")
    p.add_argument("--max-questions", type=int, default=None)
    p.add_argument("--label", default=None, help="Row name in vs-literature tables")
    args = p.parse_args(argv)

    cfg: dict[str, Any] = {}
    cfg_path = Path(args.config)
    if cfg_path.is_file():
        cfg = load_config(cfg_path)
    acfg = cfg.get("autorater") or {}
    provider = args.autorater or acfg.get("provider") or "openai"
    model = args.model or acfg.get("model") or DEFAULT_AUTORATER_MODEL
    temperature = (
        args.temperature
        if args.temperature is not None
        else float(acfg.get("temperature", 0.0))
    )
    max_tokens_raw = (
        args.max_tokens
        if args.max_tokens is not None
        else acfg.get("max_tokens")
    )
    max_tokens = int(max_tokens_raw) if max_tokens_raw is not None else None
    prompt_path = args.prompt or acfg.get("prompt_path")
    pred_path, out_dir = _resolve_run_paths(args.run, args.predictions, args.out)

    judge_label = "mock (configured live model ignored)" if provider == "mock" else f"{provider}/{model}"
    print(
        f"Autorater benchmark: predictions={pred_path} | "
        f"judge={judge_label} | out={out_dir}"
    )
    rater = get_autorater(
        provider,
        model=model,
        temperature=temperature,
        max_tokens=max_tokens,
        max_retries=int(acfg.get("max_retries", 8)),
        min_request_interval_s=float(acfg.get("min_request_interval_s", 0.5)),
        max_wait_s=float(acfg.get("max_wait_s", 3600.0)),
        prompt_path=prompt_path,
    )
    result = run_benchmark(
        pred_path,
        out_dir=out_dir,
        autorater=rater,
        skip_category=int(acfg.get("skip_category", ADVERSARIAL_CATEGORY)),
        max_questions=args.max_questions,
        our_label=args.label,
        prompt_version=Path(str(prompt_path or "autorater_mem0_v1")).stem,
    )
    metrics = result["summary"]["metrics"]
    print("Wrote", result["out_dir"])
    score_name = "mock sanity (not J)" if provider == "mock" else "J"
    print(
        f"Mem0 F1/B1/{score_name} (%):",
        metrics.get("mem0_f1_pct"),
        metrics.get("mem0_bleu1_pct"),
        metrics.get("llm_judge_pct"),
    )
    for plot in result["plots"]:
        print("Plot:", plot)


if __name__ == "__main__":
    main()
