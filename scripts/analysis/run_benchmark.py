def write_benchmark_plots(
    scored_rows: list[dict[str, Any]],
    summary: dict[str, Any],
    *,
    our_label: str,
    out_dir: Path,
) -> list[Path]:
    judged = [r for r in scored_rows if not r.get("skipped")]
    plots_dir = Path(out_dir)
    written: list[Path] = []

    js = [float(r["llm_score"]) for r in judged]
    f1s = [float(r["mem0_f1"]) for r in judged]
    b1s = [float(r["mem0_bleu1"]) for r in judged]
    reader_lat = [
        float(r["reader_latency_s"])
        for r in scored_rows
        if r.get("reader_latency_s") is not None
    ]
    judge_lat = [
        float(r["autorater_latency_s"])
        for r in judged
        if r.get("autorater_latency_s") is not None
    ]
    is_mock = summary.get("autorater_provider") == "mock"
    score_name = "Mock overlap sanity score" if is_mock else "LLM-as-a-Judge"

    for path in (
        write_count_bars(
            {
                "CORRECT": sum(1 for score in js if score == 1.0),
                "WRONG": sum(1 for score in js if score == 0.0),
            },
            path=plots_dir / "judge_verdict_barplot.png",
            ylabel="Number of questions",
            title=f"{score_name}: verdict counts",
        ),
        write_histogram(
            f1s,
            path=plots_dir / "mem0_f1_histogram.png",
            xlabel="Mem0 F1",
            title="Mem0 F1 histogram",
            bins=10,
            value_range=(0.0, 1.0),
        ),
        write_boxplot(
            {"Mem0 F1": f1s, "BLEU-1": b1s},
            path=plots_dir / "lexical_scores_boxplot.png",
            ylabel="Score (0–1)",
            title="Mem0 F1 / BLEU-1 distributions",
        ),
        write_histogram(
            reader_lat,
            path=plots_dir / "reader_latency_histogram.png",
            xlabel="Answer-reader latency (s)",
            title="Reader latency histogram",
            bins=10,
        ),
        write_boxplot(
            {"Reader": reader_lat, "Autorater": judge_lat},
            path=plots_dir / "latency_boxplot.png",
            ylabel="Seconds",
            title="Latency box-whisker (reader vs judge)",
        ),
    ):
        if path is not None:
            written.append(path)

    by_cat = summary.get("by_category") or {}
    cat_names = list(by_cat.keys())
    if cat_names:
        p = write_grouped_bars(
            cat_names,
            {
                "F1": [by_cat[c].get("mem0_f1_pct") for c in cat_names],
                "BLEU-1": [by_cat[c].get("mem0_bleu1_pct") for c in cat_names],
                ("Mock sanity" if is_mock else "J"): [
                    by_cat[c].get("llm_judge_pct") for c in cat_names
                ],
            },
            path=plots_dir / "by_category_bars.png",
            ylabel="Score (%)",
            title="Mem0 metrics by LoCoMo category",
        )
        if p is not None:
            written.append(p)

    our_j = (summary.get("metrics") or {}).get("llm_judge_pct")
    fig_methods = list(FIGURE4_METHODS)
    lit = table2_by_method()
    j_vals = [lit[m]["j"] if m in lit else None for m in fig_methods]
    labels = fig_methods + [our_label]
    if not is_mock:
        j_series = j_vals + [our_j]
        p = write_grouped_bars(
            labels,
            {"LLM-as-a-Judge J": j_series},
            path=plots_dir / "j_vs_literature.png",
            ylabel="J (%)",
            title="LLM-as-a-Judge vs Mem0 paper (Table 2)",
        )
        if p is not None:
            written.append(p)

    our_p50 = ((summary.get("metrics") or {}).get("reader_latency") or {}).get("p50")
    our_p95 = ((summary.get("metrics") or {}).get("reader_latency") or {}).get("p95")
    p = write_latency_p50_p95_bars(
        labels,
        [lit[m].get("total_p50") if m in lit else None for m in fig_methods] + [our_p50],
        [lit[m].get("total_p95") if m in lit else None for m in fig_methods] + [our_p95],
        path=plots_dir / "latency_vs_literature.png",
        title="Total latency p50/p95 vs Mem0 paper (Table 2)",
    )
    if p is not None:
        written.append(p)

    return written


