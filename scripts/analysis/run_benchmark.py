def _mean(values: list[float]) -> float | None:
    if not values:
        return None
    return round(sum(values) / len(values), 4)


def _as_pct(value: float | None) -> float | None:
    if value is None:
        return None
    return round(value * 100.0, 2)


def _usage_count(usage: Any, key: str) -> int | None:
    if not isinstance(usage, dict) or usage.get(key) is None:
        return None
    try:
        return int(usage[key])
    except (TypeError, ValueError):
        return None


def _reset_benchmark_output(out_dir: Path) -> None:
    """Remove only files/directories generated by this analysis.

    Autorater reports are snapshots, not append-only runs. Clearing known
    artifacts prevents mock/live, model, prompt, or source-run results from
    coexisting in one report directory. The source prediction pack is never
    touched.
    """
    for dirname in ("plots", "tables"):
        path = out_dir / dirname
        if path.is_dir():
            shutil.rmtree(path)
    for filename in (
        "autorater_verdicts.jsonl",
        "autorater_metrics.json",
        "run_meta.json",
        "SUMMARY.md",
    ):
        path = out_dir / filename
        if path.is_file():
            path.unlink()


def score_prediction_for_benchmark(
    pred_row: dict[str, Any],
    autorater: Autorater,
    *,
    skip_category: int = ADVERSARIAL_CATEGORY,
) -> dict[str, Any]:
    """Lexical Mem0 metrics + optional judge call for one prediction row."""
    question = str(pred_row.get("question") or "")
    gold = str(pred_row.get("reference_answer") or "")
    pred = str(pred_row.get("predicted_answer") or "")
    category = pred_row.get("category")
    reader_usage = pred_row.get("usage") or {}
    lexical = score_mem0_lexical(pred, gold)
    locomo = score_row(pred, gold, int(category or 0))
    reader_latency = pred_row.get("latency_s")
    try:
        reader_latency_s = float(reader_latency) if reader_latency is not None else None
    except (TypeError, ValueError):
        reader_latency_s = None

    base = {
        "sample_id": pred_row.get("sample_id"),
        "question_id": pred_row.get("question_id"),
        "category": category,
        "category_name": CATEGORY_NAMES.get(int(category or 0), str(category)),
        "question": question,
        "reference_answer": gold,
        "predicted_answer": pred,
        "memory_type": pred_row.get("memory_type"),
        "reader_model": pred_row.get("reader_model"),
        "autorater_model": autorater.model_name,
        "autorater_provider": autorater.provider,
        "mem0_f1": round(lexical["mem0_f1"], 6),
        "mem0_bleu1": round(lexical["mem0_bleu1"], 6),
        "locomo_f1": locomo["locomo_f1"],
        "token_f1": locomo["token_f1"],
        "exact_match": locomo["exact_match"],
        "reader_latency_s": reader_latency_s,
        "reader_prompt_tokens": _usage_count(reader_usage, "prompt_tokens"),
        "reader_completion_tokens": _usage_count(reader_usage, "completion_tokens"),
        "reader_total_tokens": _usage_count(reader_usage, "total_tokens"),
        "memory_chars": len(str(pred_row.get("memory_text") or "")),
    }

    if should_skip_category(category, skip_category):
        verdict = skipped_verdict(
            model=autorater.model_name,
            provider=autorater.provider,
            category=int(category),
        )
    else:
        verdict = autorater.rate(question, gold, pred)
    payload = verdict.to_dict()
    payload["autorater_latency_s"] = payload.pop("latency_s", 0.0)
    usage = payload.get("usage") or {}
    payload["autorater_prompt_tokens"] = _usage_count(usage, "prompt_tokens")
    payload["autorater_completion_tokens"] = _usage_count(usage, "completion_tokens")
    payload["autorater_total_tokens"] = _usage_count(usage, "total_tokens")
    return {**base, **payload}


def aggregate_benchmark(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Overall + by-category Mem0 F1 / BLEU-1 / J, plus latency percentiles."""
    judged = [r for r in rows if not r.get("skipped")]
    skipped = [r for r in rows if r.get("skipped")]

    def _pack(subset: list[dict[str, Any]]) -> dict[str, Any]:
        f1s = [float(r["mem0_f1"]) for r in subset]
        b1s = [float(r["mem0_bleu1"]) for r in subset]
        js = [float(r["llm_score"]) for r in subset]
        locomos = [float(r["locomo_f1"]) for r in subset if r.get("locomo_f1") is not None]
        reader_lat = [
            float(r["reader_latency_s"])
            for r in subset
            if r.get("reader_latency_s") is not None
        ]
        judge_lat = [
            float(r["autorater_latency_s"])
            for r in subset
            if r.get("autorater_latency_s") is not None and not r.get("skipped")
        ]
        reader_prompt_tokens = [
            float(r["reader_prompt_tokens"])
            for r in subset
            if r.get("reader_prompt_tokens") is not None
        ]
        reader_total_tokens = [
            float(r["reader_total_tokens"])
            for r in subset
            if r.get("reader_total_tokens") is not None
        ]
        judge_total_tokens = [
            float(r["autorater_total_tokens"])
            for r in subset
            if r.get("autorater_total_tokens") is not None and not r.get("skipped")
        ]
        memory_chars = [
            float(r["memory_chars"])
            for r in subset
            if r.get("memory_chars") is not None
        ]
        return {
            "n": len(subset),
            "mem0_f1": _mean(f1s),
            "mem0_bleu1": _mean(b1s),
            "llm_judge": _mean(js),
            "llm_judge_pct": _as_pct(_mean(js)),
            "mem0_f1_pct": _as_pct(_mean(f1s)),
            "mem0_bleu1_pct": _as_pct(_mean(b1s)),
            "locomo_f1": _mean(locomos),
            "reader_latency": summarize_latencies(reader_lat),
            "autorater_latency": summarize_latencies(judge_lat),
            "reader_prompt_tokens_mean": _mean(reader_prompt_tokens),
            "reader_total_tokens_mean": _mean(reader_total_tokens),
            "reader_total_tokens_sum": (
                round(sum(reader_total_tokens)) if reader_total_tokens else None
            ),
            "autorater_total_tokens_mean": _mean(judge_total_tokens),
            "autorater_total_tokens_sum": (
                round(sum(judge_total_tokens)) if judge_total_tokens else None
            ),
            "memory_chars_mean": _mean(memory_chars),
        }

    by_category: dict[str, Any] = {}
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in judged:
        grouped[str(r.get("category_name") or r.get("category"))].append(r)
    for name, subset in grouped.items():
        cat_id = subset[0].get("category")
        by_category[name] = {"category_id": cat_id, **_pack(subset)}

    locomo_all = _pack(rows)
    return {
        "number_of_questions": len(rows),
        "n_judged": len(judged),
        "n_skipped": len(skipped),
        "skip_category": ADVERSARIAL_CATEGORY,
        "metrics": _pack(judged),
        "metrics_including_skipped": locomo_all,
        "by_category": by_category,
    }


